export function faqJsonLd(items) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map(item => ({
      "@type": "Question",
      name: item.q.replace(/\u200f/g, ""),
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };
}

